<?php

declare(strict_types=1);

/** Build static editor methods without evaluating PHP or copying request data into the asset. */
function bloxEditorCoreSource(): string
{
    return expandBloxEditorCore(dirname(__DIR__) . '/admin/blox_editor/partials/editor-core-methods.php');
}

function expandBloxEditorCore(string $path, int $depth = 0): string
{
    if ($depth > 5) throw new RuntimeException('Editor method include depth exceeded');
    $source = file_get_contents($path);
    if ($source === false) throw new RuntimeException('Cannot read editor methods: ' . $path);
    $expanded = preg_replace_callback('/<\?php(.*?)\?>/s', static function (array $match) use ($path, $depth): string {
        $code = '';
        foreach (token_get_all('<?php ' . $match[1]) as $token) {
            if (is_array($token) && in_array($token[0], [T_OPEN_TAG, T_COMMENT, T_DOC_COMMENT, T_WHITESPACE], true)) continue;
            $code .= is_array($token) ? $token[1] : $token;
        }
        if ($code === '' || $code === 'declare(strict_types=1);') return '';
        if (preg_match("~^require__DIR__\\.'(/[a-z0-9-]+\\.php)';$~", $code, $include)) {
            return expandBloxEditorCore(dirname($path) . $include[1], $depth + 1);
        }
        throw new RuntimeException('Dynamic PHP is forbidden in the static editor runtime: ' . basename($path));
    }, $source);
    if (!is_string($expanded) || str_contains($expanded, '<?')) throw new RuntimeException('Invalid editor runtime source');
    return (string) preg_replace('/[\t ]+$/m', '', $expanded);
}

function bloxEditorRuntimeAsset(): string
{
    return "// Generated by php tools/build_blox_runtime.php; edit the method partials instead.\n"
        . "(function (global) {\n    \"use strict\";\n    global.BloxEditorRuntime = {\n        create: function (state) {\n"
        . "            var runtimeText = state.runtimeText;\n"
        . "            var draftSummaryCache = { rev: -1, key: \"\", value: null };\n"
        . "            return Object.defineProperties(state, Object.getOwnPropertyDescriptors({\n"
        . bloxEditorCoreSource()
        . "            }));\n        }\n    };\n})(window);\n";
}

if (realpath((string) ($_SERVER['SCRIPT_FILENAME'] ?? '')) === realpath(__FILE__)) {
    $target = dirname(__DIR__) . '/assets/js/yikay-editor-runtime.js';
    $asset = bloxEditorRuntimeAsset();
    $existing = is_file($target) ? file_get_contents($target) : false;
    if (in_array('--check', $argv, true)) {
        if ($existing !== $asset) {
            fwrite(STDERR, "Editor runtime is stale; run php tools/build_blox_runtime.php\n");
            exit(1);
        }
        echo "Editor runtime is up to date\n";
    } elseif ($existing !== $asset) {
        if (file_put_contents($target, $asset) === false) throw new RuntimeException('Cannot write editor runtime');
        echo 'Editor runtime built: ' . strlen($asset) . " bytes\n";
    }
}
